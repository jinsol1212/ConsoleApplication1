export function searchBasics(query: string): BasicsEntry[] {
  const q = query.trim().toLowerCase().replace(/\s+/g, '')
  if (!q) return BASICS

  const scored = BASICS.map((entry) => {
    let score = 0
    for (const key of entry.q) {
      const k = key.toLowerCase().replace(/\s+/g, '')
      if (q.includes(k) || k.includes(q)) score += 10
    }
    if (entry.title.toLowerCase().includes(query.trim().toLowerCase()))
      score += 5
    for (const tag of entry.tags) {
      if (q.includes(tag.toLowerCase())) score += 3
    }
    if (entry.body.includes(query.trim())) score += 1
    return { entry, score }
  })

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.entry)
}
